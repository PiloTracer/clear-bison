#!/usr/bin/env bash
# =============================================================================
#  ClearBison — stack control (dev | prd)
#
#  Usage:
#    ./bin/start.sh                 → interactive menu (default env: dev)
#    ./bin/start.sh dev             → interactive menu for env=dev
#    ./bin/start.sh prd             → interactive menu for env=prd
#    ./bin/start.sh <env> <cmd>     → run command for that env
#    ./bin/start.sh setup           → generate .env.dev with random ports
#    ./bin/start.sh prd setup       → generate .env.prd with random ports
#
#  Environments (owner rule):
#    dev → docker-compose.dev.yml + .env.dev  (Dockerfile.*.dev)
#    prd → docker-compose.prd.yml + .env.prd  (Dockerfile.*.prd)
#
#  Unique .env* files live ONLY at repo root (.env.example / .env.dev / .env.prd).
#  Random free API/WEB ports are generated once per env and persisted.
#  PUBLIC_HOST defaults to logicbison.com (LogicBison hosting).
# =============================================================================
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

ENVS=(dev prd)
SERVICES=(api web)

ENV="dev"
CMD=""
SERVICE=""

for arg in "$@"; do
  case "$arg" in
    dev|prd)
      if [ -z "$CMD" ]; then ENV="$arg"; continue; fi
      ;;
  esac
  if [ -z "$CMD" ]; then
    CMD="$arg"
  elif [ -z "$SERVICE" ]; then
    SERVICE="$arg"
  fi
done

ENV_FILE=".env.$ENV"
COMPOSE_FILE="docker-compose.$ENV.yml"
EXAMPLE_FILE=".env.example"

if [ -t 1 ] && [ -z "${NO_COLOR:-}" ]; then
  RED=$'\033[0;31m'; GREEN=$'\033[0;32m'; YELLOW=$'\033[0;33m'
  BOLD=$'\033[1m'; RESET=$'\033[0m'
else
  RED=""; GREEN=""; YELLOW=""; BOLD=""; RESET=""
fi

info()  { printf '%s%s%s\n' "$GREEN" "$*" "$RESET"; }
warn()  { printf '%s%s%s\n' "$YELLOW" "$*" "$RESET"; }
error() { printf '%s%s%s\n' "$RED" "$*" "$RESET" >&2; }

require_docker() {
  command -v docker >/dev/null 2>&1 || { error "docker not found"; exit 1; }
  docker compose version >/dev/null 2>&1 || { error "docker compose plugin required"; exit 1; }
}

require_env() {
  if [ ! -f "$ENV_FILE" ]; then
    error "Missing $ENV_FILE"
    printf 'Run:  ./bin/start.sh %s setup\n' "$ENV"
    exit 1
  fi
}

load_env() {
  require_env
  set -a
  # shellcheck disable=SC1090
  source "$ENV_FILE"
  set +a
  : "${COMPOSE_PROJECT_NAME:?missing COMPOSE_PROJECT_NAME in $ENV_FILE}"
  : "${API_PORT:?missing API_PORT in $ENV_FILE}"
  : "${WEB_PORT:?missing WEB_PORT in $ENV_FILE}"
  : "${PUBLIC_HOST:=logicbison.com}"
  : "${BIND_ADDRESS:=0.0.0.0}"
  : "${CONTACT_INBOX:=hello@clearbison.com}"
}

compose() {
  docker compose \
    --project-directory "$REPO_ROOT" \
    --project-name "$COMPOSE_PROJECT_NAME" \
    --env-file "$ENV_FILE" \
    -f "$COMPOSE_FILE" \
    "$@"
}

random_free_ports() {
  python3 - <<'PY'
import socket
ports = []
socks = []
for _ in range(2):
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    s.bind(("0.0.0.0", 0))
    socks.append(s)
    ports.append(s.getsockname()[1])
for s in socks:
    s.close()
print(ports[0], ports[1])
PY
}

read_dotenv_value() {
  local key="$1" file="$2"
  [ -f "$file" ] || return 0
  grep -E "^${key}=" "$file" 2>/dev/null | head -1 | cut -d= -f2- || true
}

cmd_setup() {
  require_docker
  local api_port web_port suffix project_name bak
  bak="${ENV_FILE}.bak.$(date +%Y%m%d-%H%M%S)"
  read -r api_port web_port < <(random_free_ports)
  suffix="$(python3 -c 'import secrets; print(secrets.token_hex(3))')"

  if [ -f "$ENV_FILE" ]; then
    warn "Backing up existing $ENV_FILE → $bak"
    cp "$ENV_FILE" "$bak"
  fi

  project_name="$(read_dotenv_value COMPOSE_PROJECT_NAME "${bak:-}")"
  [ -n "$project_name" ] || project_name="clearbison-${ENV}-${suffix}"

  # Carry contact / cors / public host when re-setup
  local contact cors public bind
  contact="$(read_dotenv_value CONTACT_INBOX "${bak:-}")"
  cors="$(read_dotenv_value CORS_ORIGINS "${bak:-}")"
  public="$(read_dotenv_value PUBLIC_HOST "${bak:-}")"
  bind="$(read_dotenv_value BIND_ADDRESS "${bak:-}")"
  [ -n "$contact" ] || contact="hello@clearbison.com"
  [ -n "$cors" ] || cors="*"
  [ -n "$public" ] || public="logicbison.com"
  [ -n "$bind" ] || bind="0.0.0.0"

  cat > "$ENV_FILE" <<EOF
# Generated by ./bin/start.sh $ENV setup — do not commit.
# Unique .env* files live only at repo root.
COMPOSE_PROJECT_NAME=$project_name
APP_ENV=$ENV
STACK_SUFFIX=-$ENV
PUBLIC_HOST=$public
BIND_ADDRESS=$bind

API_PORT=$api_port
WEB_PORT=$web_port

# Empty → browser uses http://PUBLIC_HOST:API_PORT (printed by status/up)
NEXT_PUBLIC_API_BASE=

CONTACT_INBOX=$contact
CORS_ORIGINS=$cors
EOF

  info "Wrote $ENV_FILE"
  info "  COMPOSE_PROJECT_NAME=$project_name"
  info "  API_PORT=$api_port  WEB_PORT=$web_port  PUBLIC_HOST=$public"
  if [ ! -f "$EXAMPLE_FILE" ]; then
    warn "Missing $EXAMPLE_FILE (expected in repo)"
  fi
}

cmd_up() {
  require_docker
  load_env
  info "Starting stack '$COMPOSE_PROJECT_NAME' [$ENV] (api:$API_PORT web:$WEB_PORT)"
  compose up -d --build
  cmd_urls
}

cmd_down() {
  require_docker
  load_env
  compose down
  info "Stopped $COMPOSE_PROJECT_NAME"
}

cmd_restart() {
  require_docker
  load_env
  compose restart ${SERVICE:-}
}

cmd_rebuild() {
  require_docker
  load_env
  if [ -n "$SERVICE" ]; then
    compose up -d --build --force-recreate "$SERVICE"
  else
    compose up -d --build --force-recreate
  fi
  cmd_urls
}

cmd_logs() {
  require_docker
  load_env
  compose logs --tail=200 ${SERVICE:-}
}

cmd_logs_follow() {
  require_docker
  load_env
  compose logs -f --tail=100 ${SERVICE:-}
}

cmd_ps() {
  require_docker
  load_env
  compose ps
}

cmd_urls() {
  load_env
  local host="$PUBLIC_HOST"
  printf '\n%sClearBison [%s]%s\n' "$BOLD" "$ENV" "$RESET"
  printf '  Web     http://%s:%s/\n' "$host" "$WEB_PORT"
  printf '  API     http://%s:%s/health\n' "$host" "$API_PORT"
  if [ "$ENV" = "dev" ]; then
    printf '  Docs    http://%s:%s/docs\n' "$host" "$API_PORT"
  fi
  printf '  Local   http://localhost:%s/  (web)  http://localhost:%s/health  (api)\n' \
    "$WEB_PORT" "$API_PORT"
  printf '\n'
}

cmd_status() {
  require_docker
  if [ -f "$ENV_FILE" ]; then
    load_env
    compose ps || true
    cmd_urls
  else
    warn "No $ENV_FILE yet — run: ./bin/start.sh $ENV setup"
  fi
}

cmd_shell() {
  require_docker
  load_env
  local svc="${SERVICE:-web}"
  compose exec "$svc" bash || compose exec "$svc" sh
}

print_menu() {
  cat <<EOF

${BOLD}ClearBison stack — env=${ENV}${RESET}
  1) setup          generate/refresh .env.${ENV} with random ports
  2) up             build + start
  3) down           stop
  4) restart        restart services
  5) rebuild        force recreate (+ optional service)
  6) logs           recent logs
  7) logs-follow    follow logs
  8) ps / status    containers + URLs
  9) urls           print URLs
  0) quit

Commands also work non-interactive:
  ./bin/start.sh ${ENV} up
  ./bin/start.sh ${ENV} rebuild web
EOF
}

interactive_menu() {
  while true; do
    print_menu
    printf 'Select: '
    read -r choice || true
    case "$choice" in
      1|setup) CMD=setup; cmd_setup ;;
      2|up) CMD=up; cmd_up ;;
      3|down) CMD=down; cmd_down ;;
      4|restart) CMD=restart; cmd_restart ;;
      5|rebuild)
        printf 'Service (api|web|empty=all): '
        read -r SERVICE || true
        CMD=rebuild; cmd_rebuild
        SERVICE=""
        ;;
      6|logs) CMD=logs; cmd_logs ;;
      7|logs-follow) CMD=logs-follow; cmd_logs_follow ;;
      8|ps|status) CMD=status; cmd_status ;;
      9|urls) CMD=urls; cmd_urls ;;
      0|q|quit) exit 0 ;;
      *) warn "Unknown choice" ;;
    esac
  done
}

case "${CMD}" in
  ""|menu) interactive_menu ;;
  setup) cmd_setup ;;
  up|start) cmd_up ;;
  down|stop) cmd_down ;;
  restart) cmd_restart ;;
  rebuild) cmd_rebuild ;;
  logs) cmd_logs ;;
  logs-follow) cmd_logs_follow ;;
  ps|status) cmd_status ;;
  urls) cmd_urls ;;
  shell) cmd_shell ;;
  *)
    error "Unknown command: $CMD"
    printf 'Try: ./bin/start.sh %s setup|up|down|status\n' "$ENV"
    exit 1
    ;;
esac
